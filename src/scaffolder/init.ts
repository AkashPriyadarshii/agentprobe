import fs from 'node:fs';
import path from 'node:path';

export interface InitOptions {
  name?: string;
  description?: string;
  dir?: string;
}

export function scaffoldAgentManifests(options: InitOptions = {}): {
  createdFiles: string[];
} {
  const targetDir = path.resolve(options.dir || process.cwd());
  const publicDir = fs.existsSync(path.join(targetDir, 'public'))
    ? path.join(targetDir, 'public')
    : targetDir;

  const projectName = options.name || path.basename(targetDir);
  const description = options.description || 'Modern web application and documentation.';

  const createdFiles: string[] = [];

  // 1. Scaffold llms.txt
  const llmsPath = path.join(publicDir, 'llms.txt');
  if (!fs.existsSync(llmsPath)) {
    const llmsContent = `# ${projectName}

> ${description}

## Quick Links
- [Documentation](/docs): Complete product and developer guides
- [API Reference](/api): Endpoints, payloads, and integration parameters
- [Changelog](/changelog): Recent updates, deprecations, and features

## About
This file is generated by agentprobe to provide structured context for AI browsing agents and LLMs.
For more details, see https://llmstxt.org.
`;
    fs.writeFileSync(llmsPath, llmsContent, 'utf-8');
    createdFiles.push(llmsPath);
  }

  // 2. Scaffold / Update robots.txt with 15 major AI bots
  const robotsPath = path.join(publicDir, 'robots.txt');
  if (!fs.existsSync(robotsPath)) {
    const robotsContent = `# AI Agent Crawlers
User-agent: GPTBot
Allow: /

User-agent: ChatGPT-User
Allow: /

User-agent: ClaudeBot
Allow: /

User-agent: anthropic-ai
Allow: /

User-agent: PerplexityBot
Allow: /

User-agent: Google-Extended
Allow: /

User-agent: Applebot-Extended
Allow: /

User-agent: Meta-ExternalAgent
Allow: /

User-agent: Amazonbot
Allow: /

User-agent: ByteSpider
Allow: /

User-agent: Diffbot
Allow: /

User-agent: cohere-ai
Allow: /

User-agent: OAI-SearchBot
Allow: /

# General Crawlers
User-agent: *
Allow: /

Sitemap: https://yourdomain.com/sitemap.xml
`;
    fs.writeFileSync(robotsPath, robotsContent, 'utf-8');
    createdFiles.push(robotsPath);
  }

  // 3. Scaffold .well-known/ai-catalog.json (Agentic Resource Discovery)
  const wellKnownDir = path.join(publicDir, '.well-known');
  if (!fs.existsSync(wellKnownDir)) {
    fs.mkdirSync(wellKnownDir, { recursive: true });
  }

  const catalogPath = path.join(wellKnownDir, 'ai-catalog.json');
  if (!fs.existsSync(catalogPath)) {
    const catalogContent = JSON.stringify(
      {
        $schema: 'https://ard.dev/schema/v1/ai-catalog.json',
        name: projectName,
        description,
        version: '1.0.0',
        protocols: ['mcp', 'openapi'],
        resources: [
          {
            type: 'documentation',
            url: '/llms.txt',
            format: 'text/markdown',
          },
        ],
      },
      null,
      2
    ) + '\n';
    fs.writeFileSync(catalogPath, catalogContent, 'utf-8');
    createdFiles.push(catalogPath);
  }

  // 4. Scaffold .well-known/mcp.json (Model Context Protocol)
  const mcpPath = path.join(wellKnownDir, 'mcp.json');
  if (!fs.existsSync(mcpPath)) {
    const mcpContent = JSON.stringify(
      {
        name: projectName,
        version: '1.0.0',
        description,
        capabilities: {
          tools: true,
          resources: true,
        },
      },
      null,
      2
    ) + '\n';
    fs.writeFileSync(mcpPath, mcpContent, 'utf-8');
    createdFiles.push(mcpPath);
  }

  return { createdFiles };
}
